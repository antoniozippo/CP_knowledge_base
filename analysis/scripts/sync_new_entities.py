"""Sync document-type nodes present in the raw graphify graph but missing from graph_v2.

The raw graph is regenerated by graphify and may surface entities that earlier
extractions missed. graph_v2.json (the simulator-facing artifact) predates such
additions. This script appends missing document nodes classified with the same
rule tables as build_graph_v2, so downstream card generation stays in sync.
"""

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from build_graph_v2 import assign_tier, classify_compartment, classify_entity_type


def find_missing_nodes(raw_nodes, v2_ids, only_ids=None):
    missing = [
        n for n in raw_nodes
        if n.get("file_type") == "document" and n["id"] not in v2_ids
    ]
    if only_ids is not None:
        wanted = set(only_ids)
        missing = [n for n in missing if n["id"] in wanted]
    return missing


def enrich(raw_node, links):
    label = raw_node["label"]
    degree = sum(
        1 for l in links if l.get("source") == raw_node["id"] or l.get("target") == raw_node["id"]
    )
    node = dict(raw_node)
    node["entity_type"] = classify_entity_type(label)
    node["compartment"] = classify_compartment(label)
    node["tier"] = assign_tier(degree)
    node.setdefault("norm_label", label.lower())
    return node


def sync(graph_v2_path, raw_graph_path, only_ids=None):
    v2 = json.loads(Path(graph_v2_path).read_text())
    raw = json.loads(Path(raw_graph_path).read_text())
    v2_ids = {n["id"] for n in v2["nodes"]}
    missing = find_missing_nodes(raw["nodes"], v2_ids, only_ids=only_ids)
    added = [enrich(n, v2["links"]) for n in missing]
    v2["nodes"].extend(added)
    summary = {
        "added": len(added),
        "ids": [n["id"] for n in added],
        "nodes_total": len(v2["nodes"]),
        "links_total": len(v2["links"]),
    }
    Path(graph_v2_path).write_text(json.dumps(v2, indent=2, ensure_ascii=False))
    return summary


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--graph-v2", default="graphify-out/graph_v2.json")
    parser.add_argument("--raw-graph", default="graphify-out/graph.json")
    parser.add_argument("--ids", nargs="*", default=None,
                        help="restrict sync to these node ids (default: all missing)")
    args = parser.parse_args(argv)
    summary = sync(args.graph_v2, args.raw_graph, only_ids=args.ids)
    print(json.dumps(summary, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
